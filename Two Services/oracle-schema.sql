-- --------------------------------------------------------------------
-- TABLE CREATION
-- --------------------------------------------------------------------

-- 1. USERS
CREATE TABLE USERS (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USERNAME VARCHAR2(50) NOT NULL UNIQUE,
    EMAIL VARCHAR2(100) NOT NULL UNIQUE,
    PASSWORD VARCHAR2(255) NOT NULL,
    FULL_NAME VARCHAR2(100),
    PHONE VARCHAR2(20),
    ACTIVE NUMBER(1) DEFAULT 1 NOT NULL,
    RESET_TOKEN VARCHAR2(255),
    RESET_TOKEN_EXPIRY TIMESTAMP,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 2. ROLES
CREATE TABLE ROLES (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NAME VARCHAR2(50) NOT NULL UNIQUE,
    DESCRIPTION VARCHAR2(255)
);

-- 3. USER_ROLES
CREATE TABLE USER_ROLES (
    USER_ID NUMBER NOT NULL,
    ROLE_ID NUMBER NOT NULL,
    CONSTRAINT PK_USER_ROLES PRIMARY KEY (USER_ID, ROLE_ID),
    CONSTRAINT FK_UR_USER FOREIGN KEY (USER_ID) REFERENCES USERS(ID) ON DELETE CASCADE,
    CONSTRAINT FK_UR_ROLE FOREIGN KEY (ROLE_ID) REFERENCES ROLES(ID) ON DELETE CASCADE
);

-- 4. STUDENTS
CREATE TABLE STUDENTS (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USER_ID NUMBER NOT NULL UNIQUE,
    ROLL_NUMBER VARCHAR2(50) NOT NULL UNIQUE,
    DEPARTMENT VARCHAR2(100),
    YEAR_OF_STUDY NUMBER,
    HOSTEL_BLOCK VARCHAR2(50),
    ROOM_NUMBER VARCHAR2(20),
    GUARDIAN_NAME VARCHAR2(100),
    GUARDIAN_PHONE VARCHAR2(20),
    STATUS VARCHAR2(20) DEFAULT 'ACTIVE',
    CONSTRAINT FK_STUDENT_USER FOREIGN KEY (USER_ID) REFERENCES USERS(ID) ON DELETE CASCADE
);

-- 5. WARDENS
CREATE TABLE WARDENS (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USER_ID NUMBER NOT NULL UNIQUE,
    EMPLOYEE_ID VARCHAR2(50) NOT NULL UNIQUE,
    ASSIGNED_BLOCK VARCHAR2(50),
    OFFICE_PHONE VARCHAR2(20),
    CONSTRAINT FK_WARDEN_USER FOREIGN KEY (USER_ID) REFERENCES USERS(ID) ON DELETE CASCADE
);

-- 6. ADMINS
CREATE TABLE ADMINS (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USER_ID NUMBER NOT NULL UNIQUE,
    ADMIN_CODE VARCHAR2(50) NOT NULL UNIQUE,
    DESIGNATION VARCHAR2(100),
    CONSTRAINT FK_ADMIN_USER FOREIGN KEY (USER_ID) REFERENCES USERS(ID) ON DELETE CASCADE
);

-- 7. ROOMS
CREATE TABLE ROOMS (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ROOM_NUMBER VARCHAR2(20) NOT NULL,
    BLOCK_NAME VARCHAR2(50) NOT NULL,
    FLOOR NUMBER,
    CAPACITY NUMBER NOT NULL,
    CURRENT_OCCUPANCY NUMBER DEFAULT 0,
    ROOM_TYPE VARCHAR2(50),
    STATUS VARCHAR2(20) DEFAULT 'AVAILABLE',
    CONSTRAINT UQ_ROOM_BLOCK UNIQUE (ROOM_NUMBER, BLOCK_NAME)
);

-- 8. ROOM_ALLOCATIONS
CREATE TABLE ROOM_ALLOCATIONS (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    STUDENT_ID NUMBER NOT NULL,
    ROOM_ID NUMBER NOT NULL,
    ALLOCATION_DATE DATE NOT NULL,
    VACATED_DATE DATE,
    STATUS VARCHAR2(20) DEFAULT 'ACTIVE',
    CONSTRAINT FK_RA_STUDENT FOREIGN KEY (STUDENT_ID) REFERENCES STUDENTS(ID) ON DELETE CASCADE,
    CONSTRAINT FK_RA_ROOM FOREIGN KEY (ROOM_ID) REFERENCES ROOMS(ID) ON DELETE CASCADE
);

-- 9. ATTENDANCE
CREATE TABLE ATTENDANCE (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    STUDENT_ID NUMBER NOT NULL,
    ATTENDANCE_DATE DATE NOT NULL,
    STATUS VARCHAR2(20) NOT NULL,
    REMARKS VARCHAR2(255),
    CONSTRAINT FK_ATT_STUDENT FOREIGN KEY (STUDENT_ID) REFERENCES STUDENTS(ID) ON DELETE CASCADE,
    CONSTRAINT UQ_STUDENT_DATE UNIQUE (STUDENT_ID, ATTENDANCE_DATE)
);

-- 10. COMPLAINTS
CREATE TABLE COMPLAINTS (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    STUDENT_ID NUMBER NOT NULL,
    TITLE VARCHAR2(150) NOT NULL,
    DESCRIPTION VARCHAR2(1000),
    CATEGORY VARCHAR2(50) NOT NULL,
    PRIORITY VARCHAR2(20) DEFAULT 'MEDIUM',
    STATUS VARCHAR2(20) DEFAULT 'PENDING',
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    RESOLVED_AT TIMESTAMP,
    CONSTRAINT FK_COMP_STUDENT FOREIGN KEY (STUDENT_ID) REFERENCES STUDENTS(ID) ON DELETE CASCADE
);

-- 11. COMPLAINT_FEEDBACK
CREATE TABLE COMPLAINT_FEEDBACK (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    COMPLAINT_ID NUMBER NOT NULL UNIQUE,
    RATING NUMBER NOT NULL,
    FEEDBACK_TEXT VARCHAR2(500),
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT FK_CF_COMPLAINT FOREIGN KEY (COMPLAINT_ID) REFERENCES COMPLAINTS(ID) ON DELETE CASCADE
);

-- 12. VISITORS
CREATE TABLE VISITORS (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    VISITOR_NAME VARCHAR2(100) NOT NULL,
    PHONE VARCHAR2(20) NOT NULL,
    RELATION VARCHAR2(50),
    GOVT_ID_TYPE VARCHAR2(50),
    GOVT_ID_NUMBER VARCHAR2(50)
);

-- 13. VISITOR_LOGS
CREATE TABLE VISITOR_LOGS (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    VISITOR_ID NUMBER NOT NULL,
    STUDENT_ID NUMBER NOT NULL,
    PURPOSE VARCHAR2(255),
    CHECK_IN_TIME TIMESTAMP NOT NULL,
    CHECK_OUT_TIME TIMESTAMP,
    APPROVAL_STATUS VARCHAR2(20) DEFAULT 'PENDING',
    CONSTRAINT FK_VL_VISITOR FOREIGN KEY (VISITOR_ID) REFERENCES VISITORS(ID) ON DELETE CASCADE,
    CONSTRAINT FK_VL_STUDENT FOREIGN KEY (STUDENT_ID) REFERENCES STUDENTS(ID) ON DELETE CASCADE
);

-- 14. LEAVE_REQUESTS
CREATE TABLE LEAVE_REQUESTS (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    STUDENT_ID NUMBER NOT NULL,
    START_DATE DATE NOT NULL,
    END_DATE DATE NOT NULL,
    REASON VARCHAR2(500) NOT NULL,
    STATUS VARCHAR2(20) DEFAULT 'PENDING',
    REMARKS VARCHAR2(255),
    APPLIED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT FK_LR_STUDENT FOREIGN KEY (STUDENT_ID) REFERENCES STUDENTS(ID) ON DELETE CASCADE
);

-- 15. MESS_MENU
CREATE TABLE MESS_MENU (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    DAY_OF_WEEK VARCHAR2(20) NOT NULL,
    MEAL_TYPE VARCHAR2(20) NOT NULL,
    ITEMS VARCHAR2(500) NOT NULL,
    CONSTRAINT UQ_DAY_MEAL UNIQUE (DAY_OF_WEEK, MEAL_TYPE)
);

-- 16. MESS_FEEDBACK
CREATE TABLE MESS_FEEDBACK (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    STUDENT_ID NUMBER NOT NULL,
    FEEDBACK_DATE DATE DEFAULT SYSDATE NOT NULL,
    MEAL_TYPE VARCHAR2(20) NOT NULL,
    RATING NUMBER NOT NULL,
    COMMENTS VARCHAR2(500),
    CONSTRAINT FK_MF_STUDENT FOREIGN KEY (STUDENT_ID) REFERENCES STUDENTS(ID) ON DELETE CASCADE
);

-- 17. FOOD_WASTAGE
CREATE TABLE FOOD_WASTAGE (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    WASTAGE_DATE DATE NOT NULL,
    MEAL_TYPE VARCHAR2(20) NOT NULL,
    WASTAGE_KG NUMBER(5,2) NOT NULL,
    REASON VARCHAR2(255)
);

-- 18. RESOURCES
CREATE TABLE RESOURCES (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    RESOURCE_NAME VARCHAR2(100) NOT NULL,
    CATEGORY VARCHAR2(50) NOT NULL,
    TOTAL_QUANTITY NUMBER NOT NULL,
    AVAILABLE_QUANTITY NUMBER NOT NULL,
    LOCATION VARCHAR2(100),
    STATUS VARCHAR2(20) DEFAULT 'OPERATIONAL'
);

-- 19. UTILITY_MONITORING
CREATE TABLE UTILITY_MONITORING (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    UTILITY_TYPE VARCHAR2(50) NOT NULL,
    BLOCK_NAME VARCHAR2(50) NOT NULL,
    READING_DATE DATE NOT NULL,
    CONSUMPTION_VALUE NUMBER(10,2) NOT NULL,
    UNIT_OF_MEASURE VARCHAR2(20) NOT NULL,
    STATUS VARCHAR2(20) DEFAULT 'NORMAL'
);

-- 20. NOTIFICATIONS
CREATE TABLE NOTIFICATIONS (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TITLE VARCHAR2(150) NOT NULL,
    MESSAGE VARCHAR2(1000) NOT NULL,
    TARGET_ROLE VARCHAR2(50) DEFAULT 'ALL',
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

